"""
Admin panel (sqladmin) for rooms. RoomBan is not registered, as before.

Each view lists its form and details fields explicitly. sqladmin's defaults would also show
reverse relations (a room's messages, memberships, …), and it can't preload the dynamic
`Room.memberships`, which would crash the Room pages.
"""

from sqladmin import ModelView
from sqladmin.filters import BooleanFilter, StaticValuesFilter
from sqlalchemy.orm import selectinload
from wtforms import SelectField

from .models import Message, Room, RoomInvitation, RoomMembership


class RoomAdmin(ModelView, model=Room):
    """Rooms. room_code is generated by Room() and is never editable (Django: readonly_fields)."""

    column_list = [Room.name, Room.room_code, Room.owner, Room.capacity, Room.created_at]
    # room_code shows here and in the list only. The password hash is never shown.
    column_details_list = [
        Room.id, Room.room_code, Room.name, Room.description, Room.capacity, Room.owner, Room.created_at,
    ]
    # room_code and password are left out: Room() fills the code, and a raw password typed
    # here would be saved unhashed.
    form_columns = [Room.name, Room.description, Room.capacity, Room.owner]


class RoomMembershipAdmin(ModelView, model=RoomMembership):
    """Who is in which room right now (the presence table)."""

    column_list = [RoomMembership.user, RoomMembership.room, RoomMembership.joined_at]
    column_details_list = [
        RoomMembership.id, RoomMembership.user, RoomMembership.room,
        RoomMembership.channel_name, RoomMembership.joined_at,
    ]
    form_columns = [RoomMembership.user, RoomMembership.room, RoomMembership.channel_name]


class RoomInvitationAdmin(ModelView, model=RoomInvitation):
    """Invitations from one friend to another into a room."""

    column_list = [
        RoomInvitation.sender, RoomInvitation.receiver, RoomInvitation.room,
        RoomInvitation.status, RoomInvitation.created_at,
    ]
    column_filters = [StaticValuesFilter(RoomInvitation.status, values=RoomInvitation.STATUS_CHOICES)]
    column_details_list = [
        RoomInvitation.id, RoomInvitation.room, RoomInvitation.sender, RoomInvitation.receiver,
        RoomInvitation.status, RoomInvitation.created_at,
    ]
    form_columns = [RoomInvitation.room, RoomInvitation.sender, RoomInvitation.receiver, RoomInvitation.status]
    # A dropdown of the allowed values, as Django showed for a field with choices.
    form_overrides = {'status': SelectField}
    form_args = {'status': {'choices': RoomInvitation.STATUS_CHOICES}}


class MessageAdmin(ModelView, model=Message):
    """Chat messages (soft-deleted ones included)."""

    column_list = [Message.sender, Message.room, Message.content, Message.created_at, Message.is_deleted]
    column_filters = [BooleanFilter(Message.is_deleted)]
    column_details_list = [
        Message.id, Message.room, Message.sender, Message.content, Message.reply_to,
        Message.created_at, Message.edited_at, Message.is_deleted,
    ]
    form_columns = [
        Message.room, Message.sender, Message.content, Message.reply_to, Message.edited_at, Message.is_deleted,
    ]

    def details_query(self, request):
        """sqladmin's details query, plus the replied-to message's sender.

        The page shows reply_to as `str(message)`, which reads `.sender`. sqladmin closes its
        session before rendering, so the sender must already be loaded or the page crashes.
        """
        return super().details_query(request).options(
            selectinload(Message.reply_to).selectinload(Message.sender)
        )
